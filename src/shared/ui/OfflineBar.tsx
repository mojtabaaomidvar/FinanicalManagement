/* §۸.۶ — نوارِ «اتصال نیست»

   چرا این نوار لازم است: §۸.۲ در خانه‌یارِ امروز اجرا نمی‌شود (یادداشتِ همان
   بند در docs/master-prompt.md) — یعنی دادهٔ مالی در کش نمی‌نشیند و کاربرِ
   آفلاین صفحه‌های خالی می‌بیند. بدونِ این نوار، آن خالی‌بودن شبیهِ «داده‌هایم
   پاک شد» به نظر می‌رسید، نه «اینترنت نیست».

   متن عمداً دو تکه است: جملهٔ اول حالت را می‌گوید، جملهٔ دوم دلیلِ خالی‌بودنِ
   صفحه را. نگفتنِ دومی همان سوءتفاهم را باقی می‌گذاشت.

   pointer-events: none در CSS — این نوار دکمه‌ای ندارد و روی محتوا شناور است،
   پس نباید لمسِ چیزی را که زیرش است بگیرد. */

import { useOnline } from "@/shared/lib/useOnline";

export function OfflineBar() {
  const online = useOnline();
  if (online) return null;

  return (
    <div className="offline-bar" role="status" aria-live="polite">
      <svg aria-hidden="true">
        <use href="#i-alert" />
      </svg>
      <div>
        <b>اتصال اینترنت نیست</b>
        <p>
          خانه‌یار داده‌های مالی را روی دستگاه نگه نمی‌دارد، پس تا وصل‌شدن نه
          چیزی نشان داده می‌شود و نه ثبت می‌گردد.
        </p>
      </div>
    </div>
  );
}
