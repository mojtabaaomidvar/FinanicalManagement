/* انتیتی‌های «تنظیمات تشخیص تراکنش از پیامک» — اجازه‌ها، نه پیامک‌ها.

   این فایل عمدا از sms.types.ts جداست، دقیقا مثل جدایی sms_settings.py از
   messaging.py در بک‌اند: آنجا «پیامک‌ها»ست و اینجا «اجازه‌ها». قاطی‌کردنشان
   یعنی کدی که پیامک نشان می‌دهد بتواند اجازه هم بدهد.

   قاعده حاکم بر کل این ماژول: هیچ‌جا حساب یا کارتی ساخته نمی‌شود. کاربر فقط
   از میان حساب‌هایی که از قبل در خانه‌یار ثبت کرده انتخاب می‌کند. */

/** فرستنده مجاز (سرشماره یا نام) که به «یک حساب مشخص» بسته شده.

    بسته‌بودن به حساب (نه به خانواده) عمدی است: اگر فرستنده خانواده‌محور بود،
    فعال‌کردن یک کارت در پیامک‌های همه حساب‌ها را باز می‌کرد. */
export interface SmsSender {
  id: string;
  accountId: string;
  /** شکل نرمال‌شده سرور (بدون فاصله/خط‌تیره/+، حروف کوچک) */
  sender: string;
}

/** شماره موبایلی که کاربر به‌عنوان «منبع مجاز» اضافه کرده.

    مهم: افزودن شماره به‌تنهایی هیچ اجازه‌ای نمی‌دهد و به معنی خواندن همه
    پیامک‌های آن شماره نیست (بند ۸). فقط می‌گوید «این منبع مجاز است»؛ اینکه
    چه چیزی بررسی شود را فعال‌بودن حساب و فرستنده‌هایش تعیین می‌کنند. */
export interface SmsNumber {
  id: string;
  memberId: string;
  /** ۰۹xxxxxxxxx */
  phone: string;
  label: string;
  /**
   * فعلا همیشه false و UI باید صادقانه «تأیید نشده» نشان دهد.
   *
   * تصمیم کاربر: بدون کد پیامکی. پس این فیلد هرگز به کاربر وعده تأییدشدن
   * نمی‌دهد؛ اگر روزی تأیید واقعی اضافه شد، همین‌جا true می‌شود.
   */
  verified: boolean;
  /** خاموش‌کردن موقت بدون حذف — تا کاربر مجبور به واردکردن دوباره نشود */
  active: boolean;
}

export interface SmsNumberInput {
  phone: string;
  label?: string | null;
}
