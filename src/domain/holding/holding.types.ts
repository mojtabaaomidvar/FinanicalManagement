/* انواع دارایی‌های بازاری — طلا/ارز/رمزارز/سهمی که کاربر «دارد».

   تفاوت بنیادی با Account: آن‌جا مبلغ ذخیره می‌شود، این‌جا فقط مقدار.
   «۲ سکه» همیشه ۲ سکه است ولی ارزشش هر روز فرق می‌کند، پس price/value
   ذخیره نمی‌شوند؛ سرور هر بار از قیمتِ روز حساب‌شان می‌کند. نتیجه این‌که
   کاربر هیچ‌وقت لازم نیست دارایی‌اش را دستی «به‌روز» کند. */

/** نوعِ دارایی — تعیین می‌کند قیمت از کدام منبعِ بازار بیاید */
export type HoldingKind = "gold" | "currency" | "crypto" | "stock";

export type Holding = {
  id: string;
  familyId: string;
  memberId: string;
  kind: HoldingKind;
  /** نمادِ بالادست؛ کلیدِ پیوند به قیمت */
  symbol: string;
  /** عکسِ لحظه‌ایِ نام هنگام ثبت — اگر نماد از بالادست حذف شد، ردیف خوانا بماند */
  name: string;
  /** واحدِ قیمت — برای ردیفِ قیمت‌خورده همیشه «تومان» است.
      سرور قیمتِ بالادست را (سهم به ریال، گاهی رمزارز به دلار) پیش از
      برگرداندن به تومان یکسان می‌کند، چون این عددها در یک جمع می‌نشینند. */
  unit: string;
  quantity: number;
  createdAt: string;
  /** قیمتِ واحد در آخرین اسنپ‌شاتِ سرور */
  price: number;
  /** quantity × price — وقتی priced=false صفر است */
  value: number;
  /** false = نمادِ این ردیف در دادهٔ امروزِ بازار پیدا نشد.
      این «صفر» با «ارزشِ صفر» فرق دارد: UI باید هشدار بدهد نه عدد. */
  priced: boolean;
};

/** فهرستِ دارایی‌ها + جمعِ ارزش.
    total فقط ردیف‌های قیمت‌خورده را جمع می‌زند، پس اگر نمادی قیمت نداشت
    جمع «کم‌تر از واقعیت» است نه غلط؛ unpriced تعدادشان را می‌گوید تا UI
    بتواند بگوید «۱ مورد قیمت ندارد». */
export type HoldingList = {
  items: Holding[];
  total: number;
  unpriced: number;
  /** true = قیمت‌ها از کشِ قدیمیِ سرور آمده‌اند (بالادست در دسترس نبوده) */
  stale: boolean;
};

/** ورودیِ افزودن — symbol/name/unit عیناً از همان ردیفِ قیمتی می‌آید که
    کاربر رویش زده؛ سرور دوباره اعتبارسنجی می‌کند. */
export type HoldingInput = {
  kind: HoldingKind;
  symbol: string;
  name: string;
  unit: string;
  quantity: number;
};

/** ویرایش — فقط مقدار. تغییرِ نماد یعنی ردیف دیگر معنایِ قبلی‌اش را ندارد،
    پس کاربر به‌جایش ردیفِ تازه می‌سازد. */
export type HoldingPatch = {
  id: string;
  quantity: number;
};
