/* §۷ — انتیتیِ اعلان (هستهٔ مشترک، نه per-domain)
   ────────────────────────────────────────────────
   §۷.۱ می‌گوید هر دامنه باید از *یک* هستهٔ اعلان بگذرد و «هرگز سیستمِ موازیِ
   per-domain» ساخته نشود. این فایل آن هسته است؛ هر منبعِ تازه باید
   `NotificationDomain` و یک شاخهٔ `NotificationRef` اضافه کند، نه فهرست و
   منطقِ خودش را.

   ── چرا این‌ها «مشتق‌شده»اند و جدول ندارند ──
   هر سه منبعِ فعال از دادهٔ موجود قابلِ‌استخراج‌اند، پس رونوشتشان در جدول یک
   *کش* می‌شد: رویدادِ پایه حذف شود، ردیفِ اعلان یتیم می‌ماند و فهرست دروغ
   می‌گوید. و هر سه **خودپاک‌کن**‌اند (سررسید رسیدگی شود، درخواست تأیید/رد شود،
   رویداد بگذرد → خودش می‌رود)، پس «خوانده/نخوانده» کارِ اضافهٔ بی‌معنی بود.
   یادداشتِ تاریخ‌دارِ زیرِ §7.1 در docs/master-prompt.md.

   ── متن این‌جا ساخته نمی‌شود ──
   عمداً هیچ رشتهٔ آماده‌ای برای نمایش برنمی‌گردانیم و فقط دادهٔ ساخت‌یافته و
   `ref` می‌دهیم. دو دلیل: (۱) قالب‌بندیِ مبلغ به واحدِ پولِ عضو وابسته است و
   آن کارِ لایهٔ نمایش است، نه دامنه. (۲) §۷.۵ می‌گوید اعلان نباید دادهٔ
   غیرمجاز را *در خودش جا دهد*؛ وقتی دامنه متنِ مالی نمی‌سازد، نشتی هم
   نمی‌تواند بکند. */

/** منبعِ اعلان. افزودنِ دامنهٔ تازه = یک عضوِ تازه این‌جا + یک شاخه در
 *  NotificationRef + پیش‌فرض در DEFAULT_NOTIFICATION_PREFS (هر سه را
 *  TypeScript اجبار می‌کند، پس نیمه‌کاره رها نمی‌شود). */
export type NotificationDomain =
  | "recurring"
  | "bills"
  | "event"
  | "membership"
  | "inventory";

/** شدت — ترتیبِ نمایش از همین می‌آید، نه از سلیقهٔ UI.
 *  `overdue` گذشته است · `pending` منتظرِ کنشِ شماست · `soon` خبرِ پیشاپیش. */
export type NotificationSeverity = "overdue" | "pending" | "soon";

export type NotificationRef =
  | { kind: "recurring"; txId: string; dueIso: string }
  | { kind: "bills"; billId: string; dueIso: string }
  | { kind: "event"; eventId: string; dateIso: string }
  | { kind: "membership"; requestId: string }
  /** §۴.۹ `InventoryBelowThreshold` → دامنهٔ خرید (§۷.۱).
   *  تاریخ ندارد چون **حالت** است نه رخدادِ تقویمی: «برنج تمام شده» از
   *  لحظه‌ای که موجودی زیرِ آستانه برود درست است تا وقتی پر شود. */
  | { kind: "inventory"; itemId: string };

export interface AppNotification {
  /** شناسهٔ **قطعی** (deterministic) — هرگز تصادفی نباشد.
   *
   *  چون فهرست در هر بار باز‌شدنِ نرم‌افزار از نو مشتق می‌شود، شناسه تنها
   *  چیزی است که «نادیده گرفتم» را به موردِ درست وصل می‌کند. اگر تصادفی بود،
   *  هر رندر یک شناسهٔ تازه می‌ساخت و نادیده‌گرفتن هیچ‌وقت نمی‌چسبید. */
  id: string;
  domain: NotificationDomain;
  severity: NotificationSeverity;
  /** تاریخِ مرجعِ میلادی ISO ("YYYY-MM-DD") — مبنای مرتب‌سازی.
   *  برای درخواستِ عضویت null است چون تاریخِ آینده‌ای ندارد. */
  dateIso: string | null;
  /** آیا «نادیده بگیر» می‌پذیرد.
   *  فقط رویداد true است: سررسید با رسیدگی و درخواست با تأیید/رد خودشان
   *  می‌روند، پس دادنِ «نادیده بگیر» به آن‌ها راهی برای *پنهان‌کردنِ* کارِ
   *  انجام‌نشده می‌ساخت. */
  dismissible: boolean;
  ref: NotificationRef;
}

/** §۷.۳ کلیدِ کلی + کلیدهای per-domain · §۷.۴ زمانِ پیش‌هنگامِ هر دامنه.
 *
 *  «ساعاتِ سکوت»ِ §۷.۳ عمداً این‌جا نیست: به‌حکمِ متنِ خودِ آن بند فقط پوش را
 *  مهار می‌کند و اعلانِ درون‌نرم‌افزاری «طبقِ معمول در صف می‌ماند». با نبودِ
 *  کانالِ پوش، فیلدش کلیدی می‌شد که هیچ رفتاری را عوض نمی‌کند. */
export interface NotificationPrefs {
  enabled: boolean;
  domains: Record<NotificationDomain, boolean>;
  /** روزهای پیش‌هنگام. صفر = «فقط وقتی رسید/در انتظار است». */
  leadDays: Record<NotificationDomain, number>;
}

