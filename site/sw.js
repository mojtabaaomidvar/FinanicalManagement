/* ------------------------------------------------------------------
   sw.js — «خودکشِ» سرویس‌ورکرِ قدیمی روی ریشه

   چرا این فایل اینجاست؟
   تا قبل از ۱۴۰۵/۰۶/۲۳ ریشهٔ khaanehyar.ir خودِ اپلیکیشن را سرو می‌کرد.
   اپلیکیشن یک service worker با scope = "/" ثبت می‌کرد که
   navigateFallback آن به /index.html اشاره داشت؛ یعنی هر ناوبری روی آن
   origin از کش پاسخ می‌گرفت. حالا که ریشه به سایت معرفی تبدیل شده، آن
   رجیستریشنِ قدیمی در مرورگرِ کاربرهای قبلی باقی مانده و همان پوستهٔ
   اپلیکیشن را برمی‌گرداند — حتی اگر nginx درست شده باشد، چون SW قبل از
   رسیدن درخواست به سرور آن را می‌گیرد.

   مرورگر به‌طور خودکار هر بار /sw.js را برای بررسی به‌روزرسانی می‌گیرد.
   این فایل را همان‌جا می‌گذاریم تا آن بررسی، این نسخه را ببیند، خودش را
   unregister کند و کش‌ها را پاک کند. با skipWaiting بلافاصله فعال می‌شود
   (وگرنه در حالت waiting می‌ماند تا همهٔ تب‌ها بسته شوند).

   این فایل یک تلهٔ موقت است، نه یک SW واقعی. سایت معرفی آفلاین‌کار نیست
   و به هیچ service worker دیگری نیاز ندارد. اگر روزی ریشه دوباره اپ شد،
   این فایل باید حذف شود.
------------------------------------------------------------------ */

self.addEventListener("install", () => {
  // بی‌درنگ فعال شو؛ منتظر بسته‌شدن تب‌ها نمان.
  self.skipWaiting();
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    (async () => {
      // ۱) همهٔ کش‌ها را پاک کن — پوستهٔ اپلیکیشن و دارایی‌هایش اینجا هستند.
      try {
        const keys = await caches.keys();
        await Promise.all(keys.map((k) => caches.delete(k)));
      } catch (_) {
        /* کش در دسترس نبود — ادامه بده */
      }

      // ۲) خودت را از مرورگر حذف کن.
      try {
        await self.registration.unregister();
      } catch (_) {
        /* اگر نشد، بالاخره با ۴۰۴ شدن در بررسی بعدی حذف می‌شود */
      }

      // ۳) هر تبِ باز را دوباره بارگذاری کن تا از شبکه بیاید.
      try {
        const list = await self.clients.matchAll({ type: "window" });
        for (const c of list) {
          try {
            c.navigate(c.url);
          } catch (_) {
            /* بعضی کلاینت‌ها قابل navigate نیستند */
          }
        }
      } catch (_) {
        /* بی‌خیال */
      }
    })()
  );
});

// تا وقتی این نسخه فعال نشده، هیچ درخواستی را رهگیری نکن.
// (اگر رهگیری کنیم، همان مشکل قبلی تکرار می‌شود.)
